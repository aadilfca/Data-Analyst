"""Owned P10 fixture only: existing venv/Chromium, no production credentials."""
import sys
from urllib.parse import urlparse
from playwright.sync_api import sync_playwright, expect

base = sys.argv[1]
assert urlparse(base).hostname in ("localhost", "127.0.0.1")
with sync_playwright() as playwright:
    browser = playwright.chromium.launch(headless=True)
    context = browser.new_context()
    page = context.new_page()
    page.on("dialog", lambda dialog: dialog.accept())
    page.goto(base + "/static/login.html")
    page.locator("#usernameInput").fill("shell-user")
    page.locator("#passwordInput").fill("p10-synthetic")
    page.locator("#loginSubmitBtn").click()
    expect(page).to_have_url(base + "/shell/tenant_select.html")
    page.get_by_role("button", name="Firm A — CA firm", exact=True).click()
    expect(page).to_have_url(base + "/static/client_select.html")
    expect(page.locator(".module-card")).to_have_count(1)
    expect(page.locator(".module-card")).to_contain_text("Alpha")
    page.evaluate("sessionStorage.setItem('p10-old-cache', 'old-workspace')")
    old_tab = context.new_page()
    old_tab.goto(base + "/static/clients.html")
    expect(old_tab.locator("#clientsBody")).to_be_visible()
    page.bring_to_front()
    page.locator(".module-card").click()
    expect(page).to_have_url(base + "/static/index.html")
    expect(page.get_by_role("link", name="Change workspace", exact=True)).to_be_visible()
    page.get_by_role("link", name="Change workspace", exact=True).click()
    page.get_by_role("button", name="Firm B — CA firm", exact=True).click()
    expect(page).to_have_url(base + "/static/client_select.html")
    expect(page.locator(".module-card")).to_have_count(1)
    expect(page.locator(".module-card")).to_contain_text("Beta")
    assert page.evaluate("sessionStorage.getItem('p10-old-cache')") is None
    old_tab.bring_to_front()
    expect(old_tab).to_have_url(base + "/shell/tenant_select.html")
    page.bring_to_front()
    page.locator(".module-card").click()
    expect(page).to_have_url(base + "/static/index.html")
    page.locator(".nav-logout-btn").click()
    expect(page).to_have_url(base + "/static/login.html")
    page.goto(base + "/static/clients.html")
    expect(page).to_have_url(base + "/static/login.html")
    browser.close()
print("P10 browser workflow passed")
